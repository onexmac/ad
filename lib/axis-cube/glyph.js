/** A line of the letters as one SVG path in the letters' own pixels (7 apart, 7 high), for a viewBox of w by 7. */
export function pixelPath(text) {
  let d = '';
  for (let c = 0; c < text.length; c++) {
    const rows = GLYPH[text[c]]; if (!rows) continue;
    for (let r = 0; r < 7; r++) for (let i = 0; i < 5; i++) if (rows[r] & (16 >> i)) d += 'M' + (c * 7 + i) + ' ' + r + 'h1v1h-1z';
  }
  return { d, w: Math.max(1, text.length * 7 - 2), h: 7 };
}
